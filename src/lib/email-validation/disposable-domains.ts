export function isDisposableDomain(domain: string): boolean {
  let host = domain.trim().toLowerCase().replace(/\.$/, '')
  while (host.includes('.')) {
    if (DISPOSABLE.has(host)) return true
    host = host.slice(host.indexOf('.') + 1)
  }
  return false
}
